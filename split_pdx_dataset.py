#!/usr/bin/env python3
"""
Split a YOLO-format dataset generated by movement_window.py into
train/valid/test splits, similar to the Cyclist_Pedestrian_Dataset layout.

This script supports:
- Initial splitting of a dataset with only train split
- Re-splitting after adding more training data (combines all splits and re-distributes)
- Automatic support for cyclist and pedestrian classes (matching Cyclist_Pedestrian_Dataset format)

Assumptions:
- The source dataset directory (default: pdx_cyclist_dataset) has:
    - train/images, train/labels (required)
    - valid/images, valid/labels (optional, for re-splitting)
    - test/images, test/labels (optional, for re-splitting)

Result:
- The same dataset directory will contain:
    - train/images, train/labels
    - valid/images, valid/labels
    - test/images,  test/labels
- data.yaml will be updated with proper train/val/test paths and class names.

Usage:
    # Initial split
    python split_pdx_dataset.py \
        --dataset-dir pdx_cyclist_dataset \
        --train-ratio 0.7 \
        --val-ratio 0.2 \
        --test-ratio 0.1 \
        --seed 42
    
    # Re-split after adding more data
    python split_pdx_dataset.py \
        --dataset-dir pdx_cyclist_dataset \
        --train-ratio 0.7 \
        --val-ratio 0.2 \
        --test-ratio 0.1 \
        --seed 42 \
        --allow-resplit
"""

import argparse
import random
import shutil
from pathlib import Path
from typing import Dict, List, Optional, Tuple

import yaml


IMAGE_EXTENSIONS = {".jpg", ".jpeg", ".png", ".bmp"}


def list_images(images_dir: Path) -> List[Path]:
    """Return a sorted list of image files in the given directory."""
    if not images_dir.exists():
        raise FileNotFoundError(f"Images directory does not exist: {images_dir}")

    images = [
        p for p in images_dir.iterdir()
        if p.is_file() and p.suffix.lower() in IMAGE_EXTENSIONS
    ]
    images.sort()
    return images


def ensure_split_dirs(dataset_dir: Path):
    """Ensure train/valid/test images/labels directories exist."""
    for split in ["train", "valid", "test"]:
        split_dir = dataset_dir / split
        (split_dir / "images").mkdir(parents=True, exist_ok=True)
        (split_dir / "labels").mkdir(parents=True, exist_ok=True)


def update_data_yaml(dataset_dir: Path):
    """
    Create or update data.yaml in the dataset directory so that it
    points to the new train/valid/test splits.
    
    Defaults to cyclist and pedestrian classes to match Cyclist_Pedestrian_Dataset format.
    """
    yaml_path = dataset_dir / "data.yaml"

    # Default to cyclist and pedestrian classes (matching Cyclist_Pedestrian_Dataset format)
    names = ["cyclist", "pedestrian"]
    nc = 2

    if yaml_path.exists():
        try:
            with open(yaml_path, "r") as f:
                data = yaml.safe_load(f) or {}
            if isinstance(data.get("names"), list) and data.get("names"):
                names = data["names"]
                nc = data.get("nc", len(names))
        except Exception:
            # Fall back to defaults if the existing file is malformed
            pass

    # Ensure we have at least cyclist and pedestrian
    if "cyclist" not in names:
        names.insert(0, "cyclist")
    if "pedestrian" not in names:
        names.append("pedestrian")
    nc = len(names)

    new_yaml = {
        "names": names,
        "nc": nc,
        # Use paths relative to this dataset directory
        "train": "train/images",
        "val": "valid/images",
        "test": "test/images",
    }

    with open(yaml_path, "w") as f:
        yaml.safe_dump(new_yaml, f, sort_keys=False, default_flow_style=False)

    print(f"Updated dataset config at: {yaml_path}")
    print(f"  Classes: {names} (nc={nc})")


def collect_all_images(dataset_dir: Path) -> Tuple[List[Path], Dict[Path, Optional[Path]]]:
    """
    Collect all images from train/valid/test splits and return them along with
    a mapping of image paths to their corresponding label paths.
    This allows re-splitting existing splits.
    
    Returns:
        Tuple of (list of image paths, dict mapping image_path -> label_path)
    """
    all_images = []
    image_to_label = {}
    
    # Check all splits for images and their corresponding labels
    for split in ["train", "valid", "test"]:
        split_images_dir = dataset_dir / split / "images"
        split_labels_dir = dataset_dir / split / "labels"
        
        if split_images_dir.exists():
            images = list_images(split_images_dir)
            print(f"Found {len(images)} images in {split}/images")
            
            for img_path in images:
                all_images.append(img_path)
                
                # Look for corresponding label in the same split first
                label_name = img_path.with_suffix(".txt").name
                label_path = split_labels_dir / label_name
                
                if label_path.exists():
                    image_to_label[img_path] = label_path
                else:
                    # Label not found in same split, will search in move_pair
                    image_to_label[img_path] = None
    
    if not all_images:
        raise RuntimeError(f"No images found in any split of {dataset_dir}")
    
    # Count how many images have labels
    images_with_labels = sum(1 for label_path in image_to_label.values() if label_path is not None)
    print(f"Collected {len(all_images)} total images ({images_with_labels} with labels found)")
    
    return all_images, image_to_label


def split_dataset(
    dataset_dir: Path,
    train_ratio: float,
    val_ratio: float,
    test_ratio: float,
    seed: int = 42,
    allow_resplit: bool = True,
):
    """
    Perform the actual split by moving images/labels into train/valid/test.
    
    If allow_resplit is True and valid/test already have files, all images
    from all splits will be collected and re-split according to the ratios.
    """
    if train_ratio <= 0 or val_ratio < 0 or test_ratio < 0:
        raise ValueError("Ratios must be non-negative, and train_ratio must be > 0.")

    total_ratio = train_ratio + val_ratio + test_ratio
    if total_ratio <= 0:
        raise ValueError("Sum of ratios must be > 0.")

    # Normalize ratios so they sum exactly to 1.0
    train_ratio /= total_ratio
    val_ratio /= total_ratio
    test_ratio /= total_ratio

    # Ensure output structure exists
    ensure_split_dirs(dataset_dir)

    # Check if we need to re-split (valid/test already have files)
    valid_images_dir = dataset_dir / "valid" / "images"
    test_images_dir = dataset_dir / "test" / "images"
    needs_resplit = any(valid_images_dir.glob("*")) or any(test_images_dir.glob("*"))
    
    if needs_resplit and not allow_resplit:
        raise RuntimeError(
            f"valid/test directories in {dataset_dir} are not empty. "
            "Use --allow-resplit to re-split the dataset."
        )

    # Collect all images from all splits (for re-splitting or initial split)
    all_images, image_to_label = collect_all_images(dataset_dir)
    n = len(all_images)
    
    if n == 0:
        raise RuntimeError(f"No images found in any split of {dataset_dir}")

    if needs_resplit:
        print(f"Re-splitting dataset: found {n} images across all splits")
    else:
        print(f"Splitting {n} images from train split")

    rng = random.Random(seed)
    rng.shuffle(all_images)

    n_train = int(n * train_ratio)
    n_val = int(n * val_ratio)
    # Ensure all remaining go to test
    n_test = n - n_train - n_val

    train_images = all_images[:n_train]
    val_images = all_images[n_train:n_train + n_val]
    test_images = all_images[n_train + n_val:]

    print(f"Total images: {n}")
    print(f"Train: {len(train_images)}, Val: {len(val_images)}, Test: {len(test_images)}")

    # Helper to move a single image/label pair
    def move_pair(img_path: Path, target_split: str):
        target_images_dir = dataset_dir / target_split / "images"
        target_labels_dir = dataset_dir / target_split / "labels"

        label_name = img_path.with_suffix(".txt").name
        
        # Get the label path from our mapping (collected earlier)
        src_label = image_to_label.get(img_path)
        
        # If not found in mapping, search all splits for the label
        if src_label is None or not src_label.exists():
            for split in ["train", "valid", "test"]:
                potential_label = dataset_dir / split / "labels" / label_name
                if potential_label.exists():
                    src_label = potential_label
                    break
            else:
                src_label = None

        # Move image if it's not already in the correct place
        dst_img = target_images_dir / img_path.name
        if img_path.resolve() != dst_img.resolve():
            shutil.move(str(img_path), str(dst_img))

        # Move label if it exists and needs to be moved
        if src_label is not None and src_label.exists():
            dst_label = target_labels_dir / src_label.name
            if src_label.resolve() != dst_label.resolve():
                shutil.move(str(src_label), str(dst_label))
        elif src_label is None:
            print(f"Warning: Label file not found for image {img_path.name}")

    # Move all images to their target splits
    for img in train_images:
        move_pair(img, "train")
    
    for img in val_images:
        move_pair(img, "valid")

    for img in test_images:
        move_pair(img, "test")

    # Sanity check: count images in each split
    final_train = list_images(dataset_dir / "train" / "images")
    final_val = list_images(dataset_dir / "valid" / "images")
    final_test = list_images(dataset_dir / "test" / "images")
    print(
        f"Final counts -> train: {len(final_train)}, "
        f"valid: {len(final_val)}, test: {len(final_test)}"
    )


def main():
    parser = argparse.ArgumentParser(
        description="Split movement_window.py-generated dataset into train/valid/test."
    )
    parser.add_argument(
        "--dataset-dir",
        type=str,
        default="pdx_cyclist_dataset",
        help="Path to the dataset directory created by movement_window.py "
             "(containing train/images and train/labels).",
    )
    parser.add_argument(
        "--train-ratio",
        type=float,
        default=0.7,
        help="Proportion of images to keep in the train split (before normalization).",
    )
    parser.add_argument(
        "--val-ratio",
        type=float,
        default=0.2,
        help="Proportion of images to move to the validation split (before normalization).",
    )
    parser.add_argument(
        "--test-ratio",
        type=float,
        default=0.1,
        help="Proportion of images to move to the test split (before normalization).",
    )
    parser.add_argument(
        "--seed",
        type=int,
        default=42,
        help="Random seed for reproducible shuffling.",
    )
    parser.add_argument(
        "--allow-resplit",
        action="store_true",
        help="Allow re-splitting when valid/test directories already contain files. "
             "All images from all splits will be collected and re-distributed.",
    )

    args = parser.parse_args()
    dataset_dir = Path(args.dataset_dir)

    if not dataset_dir.exists():
        raise FileNotFoundError(f"Dataset directory does not exist: {dataset_dir}")

    split_dataset(
        dataset_dir=dataset_dir,
        train_ratio=args.train_ratio,
        val_ratio=args.val_ratio,
        test_ratio=args.test_ratio,
        seed=args.seed,
        allow_resplit=args.allow_resplit,
    )
    update_data_yaml(dataset_dir)


if __name__ == "__main__":
    main()


